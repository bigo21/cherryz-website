import { redirect } from "next/navigation";
import { CodeForm } from "@/components/admin/AuthForms";
import { card } from "@/components/admin/ui";
import { getAdminState, safeNext } from "@/lib/admin/dal";

// First sign-in of a member: links an authenticator app (TOTP) to the account.
export default async function Securite({ searchParams }: { searchParams: Promise<{ suite?: string }> }) {
  const suite = safeNext((await searchParams).suite);
  const state = await getAdminState();
  if (state.step === "signed-out") redirect("/admin/connexion");
  if (state.step === "not-member") redirect("/admin/refus");
  if (state.step === "verify") redirect(`/admin/verification?suite=${encodeURIComponent(suite)}`);
  if (state.step === "ready") redirect(suite);

  // A set-up left half-done (page closed before the code) is dropped, so each
  // visit starts from one fresh QR code.
  const mfa = state.supabase.auth.mfa;
  const { data: factors } = await mfa.listFactors();
  for (const f of factors?.all ?? []) {
    if (f.factor_type === "totp" && f.status !== "verified") await mfa.unenroll({ factorId: f.id });
  }
  const { data, error } = await mfa.enroll({
    factorType: "totp",
    issuer: "Cherryz équipe",
    friendlyName: `Application d'authentification ${new Date().toISOString().slice(0, 10)}`,
  });
  if (error || !data) throw new Error("Impossible de préparer la double authentification. Réessayez.");

  return (
    <div className={`${card} mx-auto max-w-[520px] px-6 py-8 sm:px-9`}>
      <h1 className="m-0 font-condensed text-[32px] font-bold leading-[1.05]">Activez la double authentification</h1>
      <ol className="mb-6 mt-3 grid gap-2 pl-5 font-sans text-[15.5px] text-navy/75">
        <li>Ouvrez une application d&apos;authentification (Google Authenticator, Microsoft Authenticator, 1Password…).</li>
        <li>Scannez ce QR code, ou saisissez la clé ci-dessous.</li>
        <li>Entrez le code à 6 chiffres qu&apos;elle affiche.</li>
      </ol>
      {/* The QR code is an SVG data URL generated by Supabase Auth. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={data.totp.qr_code} alt="QR code à scanner avec l'application d'authentification" width={200} height={200} className="mx-auto block rounded-xl bg-white p-2" />
      <p className="mb-6 mt-3 break-all text-center font-mono text-[14px] text-navy/70">{data.totp.secret}</p>
      <CodeForm suite={suite} factorId={data.id} />
    </div>
  );
}
